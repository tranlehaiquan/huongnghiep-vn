/**
 * slugify.ts — Convert Vietnamese school names to URL-safe ASCII slugs
 * Used in both getStaticPaths() (school detail) and links (school index/home)
 */

const ACCENT_MAP: Record<string, string> = {
  'à':'a','á':'a','ả':'a','ã':'a','ạ':'a',
  'ă':'a','ắ':'a','ặ':'a','ằ':'a','ẳ':'a','ẵ':'a',
  'â':'a','ấ':'a','ậ':'a','ầ':'a','ẩ':'a','ẫ':'a',
  'è':'e','é':'e','ẻ':'e','ẽ':'e','ẹ':'e',
  'ê':'e','ế':'e','ệ':'e','ề':'e','ể':'e','ễ':'e',
  'ì':'i','í':'i','ỉ':'i','ĩ':'i','ị':'i',
  'ò':'o','ó':'o','ỏ':'o','õ':'o','ọ':'o',
  'ô':'o','ố':'o','ộ':'o','ồ':'o','ổ':'o','ỗ':'o',
  'ơ':'o','ớ':'o','ợ':'o','ờ':'o','ở':'o','ỡ':'o',
  'ù':'u','ú':'u','ủ':'u','ũ':'u','ụ':'u',
  'ư':'u','ứ':'u','ự':'u','ừ':'u','ử':'u','ữ':'u',
  'ỳ':'y','ý':'y','ỷ':'y','ỹ':'y','ỵ':'y',
  'đ':'d',
  'À':'A','Á':'A','Ả':'A','Ã':'A','Ạ':'A',
  'Ă':'A','Ắ':'A','Ặ':'A','Ằ':'A','Ẳ':'A','Ẵ':'A',
  'Â':'A','Ấ':'A','Ậ':'A','Ầ':'A','Ẩ':'A','Ẫ':'A',
  'È':'E','É':'E','Ẻ':'E','Ẽ':'E','Ẹ':'E',
  'Ê':'E','Ế':'E','Ệ':'E','Ề':'E','Ể':'E','Ễ':'E',
  'Ì':'I','Í':'I','Ỉ':'I','Ĩ':'I','Ị':'I',
  'Ò':'O','Ó':'O','Ỏ':'O','Õ':'O','Ọ':'O',
  'Ô':'O','Ố':'O','Ộ':'O','Ồ':'O','Ổ':'O','Ỗ':'O',
  'Ơ':'O','Ớ':'O','Ợ':'O','Ờ':'O','Ở':'O','Ỡ':'O',
  'Ù':'U','Ú':'U','Ủ':'U','Ũ':'U','Ụ':'U',
  'Ư':'U','Ứ':'U','Ự':'U','Ừ':'U','Ử':'U','Ữ':'U',
  'Ỳ':'Y','Ý':'Y','Ỷ':'Y','Ỹ':'Y','Ỵ':'Y',
  'Đ':'D',
};

export function slugify(name: string): string {
  return name
    .split('')
    .map(c => ACCENT_MAP[c] || c)
    .join('')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}
